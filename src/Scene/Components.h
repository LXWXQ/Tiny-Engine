inline AABB transformAABB(const AABB& local, const glm::mat4& transform)
{
    if (!local.valid)
        return AABB{};

    AABB world;
    world.valid = true;

    const glm::vec3 corners[8] = {
        { local.min.x, local.min.y, local.min.z },
        { local.max.x, local.min.y, local.min.z },
        { local.min.x, local.max.y, local.min.z },
        { local.max.x, local.max.y, local.min.z },
        { local.min.x, local.min.y, local.max.z },
        { local.max.x, local.min.y, local.max.z },
        { local.min.x, local.max.y, local.max.z },
        { local.max.x, local.max.y, local.max.z },
    };

    world.min = glm::vec3(transform * glm::vec4(corners[0], 1.0f));
    world.max = world.min;

    for (int i = 1; i < 8; ++i)
    {
        const glm::vec3 p = glm::vec3(transform * glm::vec4(corners[i], 1.0f));
        world.min = glm::min(world.min, p);
        world.max = glm::max(world.max, p);
    }

    return world;
}