// D-7: EnTT component set. Transform stays local; WorldTransformComponent is
// generated by Scene::updateWorldTransforms() after hierarchy propagation.
struct TransformComponent
{
    // B-06: fields are private so every mutation goes through a setter that
    // bumps the dirty revision and notifies the owning Scene. Read-only
    // access is explicit; there is intentionally no mutable field reference.
    const glm::vec3& getTranslation() const { return translation; }
    const glm::vec3& getScale() const { return scale; }
    const glm::vec3& getEuler() const { return rotation; }
    const glm::quat& getOrientation() const { return orientation; }
    uint64_t getLocalRevision() const { return localRevision; }
    bool isDirty() const { return dirty; }
    void clearDirty() { dirty = false; }

    // 与旧 localMatrix() 的 T*Ry*Rx*Rz*S 完全等价：
    //   q = qy * qx * qz
    static glm::quat quatFromEuler(const glm::vec3& e)
    {
        return glm::angleAxis(e.y, glm::vec3(0.0f, 1.0f, 0.0f)) *
               glm::angleAxis(e.x, glm::vec3(1.0f, 0.0f, 0.0f)) *
               glm::angleAxis(e.z, glm::vec3(0.0f, 0.0f, 1.0f));
    }

    // 从 R = Ry(y) * Rx(x) * Rz(z) 反解欧拉角，仅用于显示/序列化。
    // 注意 GLM 的 mat3 是列主序：R[col][row]。
    static glm::vec3 eulerFromQuat(const glm::quat& q)
    {
        const glm::mat3 R = glm::mat3_cast(glm::normalize(q));
        const float sx = glm::clamp(-R[2][1], -1.0f, 1.0f);   // R[row=1][col=2]
        const float x = std::asin(sx);
        float y;
        float z;
        if (std::abs(sx) < 0.999999f)
        {
            y = std::atan2(R[2][0], R[2][2]);                 // R[0][2], R[2][2]
            z = std::atan2(R[0][1], R[1][1]);                 // R[1][0], R[1][1]
        }
        else
        {
            // 万向节：y/z 只能确定和/差，固定 z=0。
            y = std::atan2(-R[0][2], R[0][0]);
            z = 0.0f;
        }
        return glm::vec3(x, y, z);
    }

    // Dirty tracking: mutations through these setters notify the owning Scene
    // directly. Snapshots clear the callback before restoring and Scene rebinds
    // it after emplace, so undo/redo cannot retain a stale entity ID.
    using DirtyNotifyFn = void(*)(void*, entt::entity);

    void setDirtyOwner(void* context, DirtyNotifyFn notify, entt::entity owner)
    {
        dirtyNotifyContext = context;
        dirtyNotify = notify;
        dirtyOwner = owner;
    }

    void clearDirtyOwner()
    {
        dirtyNotifyContext = nullptr;
        dirtyNotify = nullptr;
        dirtyOwner = entt::null;
    }

    void markDirty()
    {
        ++localRevision;
        dirty = true;
        if (dirtyNotify)
            dirtyNotify(dirtyNotifyContext, dirtyOwner);
    }

    void setTranslation(const glm::vec3& value)
    {
        if (translation.x == value.x && translation.y == value.y &&
            translation.z == value.z)
            return;
        translation = value;
        markDirty();
    }

    void setScale(const glm::vec3& value)
    {
        if (scale.x == value.x && scale.y == value.y && scale.z == value.z)
            return;
        scale = value;
        markDirty();
    }

    void setEuler(const glm::vec3& e)
    {
        const glm::quat newOrientation = quatFromEuler(e);
        if (rotation.x == e.x && rotation.y == e.y && rotation.z == e.z &&
            orientation.w == newOrientation.w && orientation.x == newOrientation.x &&
            orientation.y == newOrientation.y && orientation.z == newOrientation.z)
            return;
        rotation = e;
        orientation = newOrientation;
        markDirty();
    }

    void setOrientation(const glm::quat& q)
    {
        const glm::quat newOrientation = glm::normalize(q);
        const glm::vec3 newRotation = eulerFromQuat(newOrientation);
        if (orientation.w == newOrientation.w && orientation.x == newOrientation.x &&
            orientation.y == newOrientation.y && orientation.z == newOrientation.z &&
            rotation.x == newRotation.x && rotation.y == newRotation.y &&
            rotation.z == newRotation.z)
            return;
        orientation = newOrientation;
        rotation = newRotation;
        markDirty();
    }

    // Restore an exact snapshot in one notification. Commands carry both the
    // authored Euler angles and the authoritative quaternion, so they must not
    // be reconstructed through setEuler()/setOrientation() (which would lose
    // one representation or emit duplicate dirty notifications).
    void setPose(const glm::vec3& translationValue, const glm::vec3& euler,
                 const glm::vec3& scaleValue, const glm::quat& orientationValue)
    {
        if (translation == translationValue && rotation == euler &&
            scale == scaleValue && orientation == orientationValue)
            return;
        translation = translationValue;
        rotation = euler;
        scale = scaleValue;
        orientation = orientationValue;
        markDirty();
    }

    glm::mat4 localMatrix() const
    {
        glm::mat4 transform = glm::translate(glm::mat4{ 1.0f }, translation);
        transform *= glm::mat4_cast(orientation);
        transform = glm::scale(transform, scale);
        return transform;
    }

private:
    glm::vec3 translation{ 0.0f };
    glm::vec3 scale{ 1.0f, 1.0f, 1.0f };
    // 欧拉角只用于 Inspector / 配置文件 / 相机。**矩阵由 orientation 生成**。
    // 直接写 rotation 不会同步 orientation —— 请用 setEuler()。
    glm::vec3 rotation{ 0.0f };              // Euler radians, XYZ 合成顺序
    // 旋转的唯一事实来源。用四元数而不是欧拉角，避免万向节死锁：
    // 连续拖动手柄时每帧在四元数空间复合，不会在 pitch=±90° 处丢一个自由度。
    glm::quat orientation{ 1.0f, 0.0f, 0.0f, 0.0f };

    void* dirtyNotifyContext = nullptr;
    DirtyNotifyFn dirtyNotify = nullptr;
    entt::entity dirtyOwner = entt::null;

    uint64_t localRevision = 1;
    bool dirty = true;
};

